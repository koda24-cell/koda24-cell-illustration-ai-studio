"""Restore the verified ArtCraft checkpoint subset from an Actions artifact."""
import argparse
import json
import re
import shutil
import tempfile
from pathlib import Path

from .scan import clamscan, safe_extract
from .util import sha256_file


def restore(archive, job, target):
    if clamscan([archive])["status"] != "SAFETY_CHECK_OK":
        raise ValueError("Checkpoint archive scan failed")
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        safe_extract(archive, root)
        if clamscan([root])["status"] != "SAFETY_CHECK_OK":
            raise ValueError("Extracted checkpoint scan failed")
        output = root / "artcraft-results/output"
        if (output / "job.sha256").read_text().strip() != sha256_file(job):
            raise ValueError("Checkpoint was generated by a different job definition")
        state = json.loads((output / "quality.json").read_text())
        expected_goal = json.loads(job.read_text())["quality_goal"]
        if state["goal"] != expected_goal or len(state["history"]) > 3:
            raise ValueError("Checkpoint goal or iteration count is invalid")
        names = {state["best_native"], state["best_preview"], "preview-00.png"}
        names.update(item["preview"] for item in state["history"])
        if any(not re.fullmatch(r"(?:preview-0[0-3]\.png|checkpoint-0[0-3]\.(?:pcraft|vectorcraft))", name)
               for name in names):
            raise ValueError("Invalid checkpoint path")
        target.mkdir()
        for name in names | {"quality.json", "job.sha256"}:
            shutil.copyfile(output / name, target / name)
        if (output / "before.png").exists():
            shutil.copyfile(output / "before.png", target / "before.png")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for argument in ("archive", "job", "target"):
        parser.add_argument(argument, type=Path)
    args = parser.parse_args()
    restore(args.archive, args.job, args.target)
